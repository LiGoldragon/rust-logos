/// Realizing a stored identifier as a lifetime token `'name` — a second verb on the
/// identifier noun, distinct from its value projection, for the lifetime leaves a
/// reference type and lifetime parameter share.
trait ProjectLifetime {
    fn project_lifetime<Resolver: NameResolver + ?Sized>(
        &self,
        names: &Resolver,
    ) -> Result<TokenStream, Error>;
}

impl ProjectLifetime for Identifier {
    fn project_lifetime<Resolver: NameResolver + ?Sized>(
        &self,
        names: &Resolver,
    ) -> Result<TokenStream, Error> {
        let name = names.resolve(*self)?;
        format!("'{}", name.as_str())
            .parse::<TokenStream>()
            .map_err(|error| Error::Project(error.to_string()))
    }
}

impl ProjectRust for TypeApplication {
    fn project<Resolver: NameResolver + ?Sized>(
        &self,
        names: &Resolver,
    ) -> Result<TokenStream, Error> {
        let head = self.head.project(names)?;
        let arguments = self
            .arguments
            .iter()
            .map(|argument| argument.project(names))
            .collect::<Result<Vec<_>, _>>()?;
        // The `<…>` re-sugaring — one of the five allowed syntheses.
        Ok(quote! { #head<#(#arguments),*> })
    }
}

impl ProjectRust for Visibility {
    fn project<Resolver: NameResolver + ?Sized>(
        &self,
        names: &Resolver,
    ) -> Result<TokenStream, Error> {
        Ok(match self {
            Visibility::Public => quote! { pub },
            Visibility::Crate => quote! { pub(crate) },
            Visibility::Module(path) => {
                let path = path.project(names)?;
                quote! { pub(in #path) }
            }
            // The empty token stream: the "no `pub`" special case dissolves here.
            Visibility::Private => TokenStream::new(),
        })
    }
}

impl ProjectAttributeMeta for Attribute {
    fn project_meta<Resolver: NameResolver + ?Sized>(
        &self,
        names: &Resolver,
    ) -> Result<TokenStream, Error> {
        match self {
            Attribute::Derive(group) => group.project(names),
            Attribute::ToolPath(path) => path.project(names),
            Attribute::HelperDerive(helper) => helper.project(names),
            Attribute::Configuration(configuration) => configuration.project(names),
            Attribute::Cfg(predicate) => {
                let predicate = predicate.project(names)?;
                Ok(quote! { cfg(#predicate) })
            }
        }
    }
}

impl ProjectRust for Attribute {
    fn project<Resolver: NameResolver + ?Sized>(
        &self,
        names: &Resolver,
    ) -> Result<TokenStream, Error> {
        let meta = self.project_meta(names)?;
        Ok(quote! { #[#meta] })
    }
}

impl ProjectRust for DeriveGroup {
    fn project<Resolver: NameResolver + ?Sized>(
        &self,
        names: &Resolver,
    ) -> Result<TokenStream, Error> {
        let paths = self
            .paths
            .iter()
            .map(|path| path.project(names))
            .collect::<Result<Vec<_>, _>>()?;
        // A trailing comma: prettyplease preserves it in the wrapped (multi-line)
        // derive the width-heavy goldens produce, and strips it when the derive
        // stays on one line — so one emission is byte-exact in both layouts.
        Ok(quote! { derive(#(#paths,)*) })
    }
}

impl ProjectRust for HelperDerive {
    fn project<Resolver: NameResolver + ?Sized>(
        &self,
        names: &Resolver,
    ) -> Result<TokenStream, Error> {
        let path = self.path.project(names)?;
        let derived = self.derived.project(names)?;
        Ok(quote! { #path(#derived) })
    }
}

impl ProjectRust for ConfigurationAttribute {
    fn project<Resolver: NameResolver + ?Sized>(
        &self,
        names: &Resolver,
    ) -> Result<TokenStream, Error> {
        let predicate = self.predicate.project(names)?;
        let inner = self.inner.project_meta(names)?;
        Ok(quote! { cfg_attr(#predicate, #inner) })
    }
}

impl ProjectRust for ConfigurationPredicate {
    fn project<Resolver: NameResolver + ?Sized>(
        &self,
        names: &Resolver,
    ) -> Result<TokenStream, Error> {
        match self {
            ConfigurationPredicate::Feature(identifier) => {
                let name = names.resolve(*identifier)?;
                let literal = syn::LitStr::new(name.as_str(), proc_macro2::Span::call_site());
                Ok(quote! { feature = #literal })
            }
        }
    }
}

impl ProjectRust for Generics {
    fn project<Resolver: NameResolver + ?Sized>(
        &self,
        names: &Resolver,
    ) -> Result<TokenStream, Error> {
        if self.parameters.is_empty() {
            return Ok(TokenStream::new());
        }
        let parameters = self
            .parameters
            .iter()
            .map(|parameter| parameter.project(names))
            .collect::<Result<Vec<_>, _>>()?;
        Ok(quote! { <#(#parameters),*> })
    }
}

impl ProjectRust for GenericParameter {
    fn project<Resolver: NameResolver + ?Sized>(
        &self,
        names: &Resolver,
    ) -> Result<TokenStream, Error> {
        match self {
            GenericParameter::Type(parameter) => parameter.project(names),
            GenericParameter::Lifetime(parameter) => parameter.project(names),
        }
    }
}

impl ProjectRust for TypeParameter {
    fn project<Resolver: NameResolver + ?Sized>(
        &self,
        names: &Resolver,
    ) -> Result<TokenStream, Error> {
        let name = self.name.project(names)?;
        if self.bounds.is_empty() {
            return Ok(name);
        }
        let bounds = self
            .bounds
            .iter()
            .map(|bound| bound.project(names))
            .collect::<Result<Vec<_>, _>>()?;
        Ok(quote! { #name: #(#bounds)+* })
    }
}

impl ProjectRust for LifetimeParameter {
    fn project<Resolver: NameResolver + ?Sized>(
        &self,
        names: &Resolver,
    ) -> Result<TokenStream, Error> {
        self.name.project_lifetime(names)
    }
}

impl ProjectRust for Field {
    fn project<Resolver: NameResolver + ?Sized>(
        &self,
        names: &Resolver,
    ) -> Result<TokenStream, Error> {
        let visibility = self.visibility.project(names)?;
        let name = self.name.project(names)?;
        let type_reference = self.type_reference.project(names)?;
        Ok(quote! { #visibility #name: #type_reference })
    }
}

impl ProjectRust for Variant {
    fn project<Resolver: NameResolver + ?Sized>(
        &self,
        names: &Resolver,
    ) -> Result<TokenStream, Error> {
        let name = self.name.project(names)?;
        match &self.payload {
            VariantPayload::Unit => Ok(name),
            VariantPayload::Tuple(types) => {
                let types = types
                    .iter()
                    .map(|type_reference| type_reference.project(names))
                    .collect::<Result<Vec<_>, _>>()?;
                Ok(quote! { #name(#(#types),*) })
            }
            VariantPayload::Struct(fields) => {
                let fields = fields
                    .iter()
                    .map(|field| field.project(names))
                    .collect::<Result<Vec<_>, _>>()?;
                Ok(quote! { #name { #(#fields),* } })
            }
        }
    }
}

impl ProjectRust for Newtype {
    fn project<Resolver: NameResolver + ?Sized>(
        &self,
        names: &Resolver,
    ) -> Result<TokenStream, Error> {
        let attributes = self.attributes.project_preamble(names)?;
        let visibility = self.visibility.project(names)?;
        let name = self.name.project(names)?;
        let wrapped_visibility = self.wrapped_visibility.project(names)?;
        let wrapped = self.wrapped.project(names)?;
        // `wrapped_visibility` is the tuple field's own visibility; `Private`
        // projects to the empty token stream, so a bare newtype emits
        // `struct Name(Wrapped);` and a `pub`-field newtype emits
        // `struct Name(pub Wrapped);` — the same node, no special case.
        Ok(quote! { #attributes #visibility struct #name(#wrapped_visibility #wrapped); })
    }
}

