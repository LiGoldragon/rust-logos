impl ProjectRust for Match {
    fn project<Resolver: NameResolver + ?Sized>(
        &self,
        names: &Resolver,
    ) -> Result<TokenStream, Error> {
        let scrutinee = self.scrutinee.project(names)?;
        let arms = self
            .arms
            .iter()
            .map(|arm| arm.project(names))
            .collect::<Result<Vec<_>, _>>()?;
        Ok(quote! { match #scrutinee { #(#arms)* } })
    }
}

impl ProjectRust for MatchArm {
    fn project<Resolver: NameResolver + ?Sized>(
        &self,
        names: &Resolver,
    ) -> Result<TokenStream, Error> {
        let pattern = self.pattern.project(names)?;
        let body = self.body.project(names)?;
        Ok(quote! { #pattern => #body, })
    }
}

impl ProjectRust for Pattern {
    fn project<Resolver: NameResolver + ?Sized>(
        &self,
        names: &Resolver,
    ) -> Result<TokenStream, Error> {
        match self {
            Pattern::Path(path) => path.project(names),
            Pattern::TupleVariant(tuple_variant) => tuple_variant.project(names),
            Pattern::Wildcard => Ok(quote! { _ }),
        }
    }
}

impl ProjectRust for TupleVariantPattern {
    fn project<Resolver: NameResolver + ?Sized>(
        &self,
        names: &Resolver,
    ) -> Result<TokenStream, Error> {
        let path = self.path.project(names)?;
        let elements = self
            .elements
            .iter()
            .map(|element| element.project(names))
            .collect::<Result<Vec<_>, _>>()?;
        Ok(quote! { #path(#(#elements),*) })
    }
}

impl ProjectRust for PatternElement {
    fn project<Resolver: NameResolver + ?Sized>(
        &self,
        names: &Resolver,
    ) -> Result<TokenStream, Error> {
        match self {
            PatternElement::Wildcard => Ok(quote! { _ }),
            PatternElement::Binding(identifier) => identifier.project(names),
        }
    }
}

impl ProjectRust for Receiver {
    fn project<Resolver: NameResolver + ?Sized>(
        &self,
        _names: &Resolver,
    ) -> Result<TokenStream, Error> {
        Ok(match self {
            Receiver::Value => quote! { self },
            Receiver::Reference => quote! { &self },
        })
    }
}

impl ProjectRust for Parameter {
    fn project<Resolver: NameResolver + ?Sized>(
        &self,
        names: &Resolver,
    ) -> Result<TokenStream, Error> {
        let name = self.name.project(names)?;
        let type_reference = self.type_reference.project(names)?;
        Ok(quote! { #name: #type_reference })
    }
}

impl ProjectRust for Block {
    fn project<Resolver: NameResolver + ?Sized>(
        &self,
        names: &Resolver,
    ) -> Result<TokenStream, Error> {
        let statements = self
            .statements
            .iter()
            .map(|statement| statement.project(names))
            .collect::<Result<Vec<_>, _>>()?;
        let tail_expression = self.tail_expression.project(names)?;
        // The `{ … }` block delimiter — one of the five allowed syntheses. The
        // statements carry their own `;`; the tail expression carries none.
        Ok(quote! { { #(#statements)* #tail_expression } })
    }
}

impl ProjectRust for Statement {
    fn project<Resolver: NameResolver + ?Sized>(
        &self,
        names: &Resolver,
    ) -> Result<TokenStream, Error> {
        match self {
            Statement::Let(let_statement) => let_statement.project(names),
            Statement::Expression(expression) => {
                let expression = expression.project(names)?;
                Ok(quote! { #expression; })
            }
        }
    }
}

impl ProjectRust for LetStatement {
    fn project<Resolver: NameResolver + ?Sized>(
        &self,
        names: &Resolver,
    ) -> Result<TokenStream, Error> {
        let mutable = match self.binding {
            LetBinding::Immutable => TokenStream::new(),
            LetBinding::Mutable => quote! { mut },
        };
        let name = self.name.project(names)?;
        let value = self.value.project(names)?;
        Ok(quote! { let #mutable #name = #value; })
    }
}

impl ProjectRust for Function {
    fn project<Resolver: NameResolver + ?Sized>(
        &self,
        names: &Resolver,
    ) -> Result<TokenStream, Error> {
        let attributes = self.attributes.project_preamble(names)?;
        let visibility = self.visibility.project(names)?;
        let name = self.name.project(names)?;
        let generics = self.generics.project(names)?;
        let mut inputs = Vec::new();
        if let Some(receiver) = &self.receiver {
            inputs.push(receiver.project(names)?);
        }
        for parameter in &self.parameters {
            inputs.push(parameter.project(names)?);
        }
        let return_type = match &self.return_type {
            None => TokenStream::new(),
            Some(type_reference) => {
                let type_reference = type_reference.project(names)?;
                quote! { -> #type_reference }
            }
        };
        let body = self.body.project(names)?;
        Ok(quote! { #attributes #visibility fn #name #generics (#(#inputs),*) #return_type #body })
    }
}

impl ProjectRust for ImplBlock {
    fn project<Resolver: NameResolver + ?Sized>(
        &self,
        names: &Resolver,
    ) -> Result<TokenStream, Error> {
        let attributes = self.attributes.project_preamble(names)?;
        let generics = self.generics.project(names)?;
        let self_type = self.self_type.project(names)?;
        let items = self
            .items
            .iter()
            .map(|item| item.project(names))
            .collect::<Result<Vec<_>, _>>()?;
        let head = match &self.implemented_trait {
            None => quote! { impl #generics #self_type },
            Some(implemented_trait) => {
                let implemented_trait = implemented_trait.project(names)?;
                quote! { impl #generics #implemented_trait for #self_type }
            }
        };
        Ok(quote! { #attributes #head { #(#items)* } })
    }
}

impl ProjectRust for ImplItem {
    fn project<Resolver: NameResolver + ?Sized>(
        &self,
        names: &Resolver,
    ) -> Result<TokenStream, Error> {
        match self {
            ImplItem::Method(function) => function.project(names),
            ImplItem::AssociatedType(associated_type) => associated_type.project(names),
            ImplItem::AssociatedConst(associated_const) => associated_const.project(names),
        }
    }
}

impl ProjectRust for AssociatedType {
    fn project<Resolver: NameResolver + ?Sized>(
        &self,
        names: &Resolver,
    ) -> Result<TokenStream, Error> {
        let name = self.name.project(names)?;
        let value = self.value.project(names)?;
        Ok(quote! { type #name = #value; })
    }
}

impl ProjectRust for Const {
    fn project<Resolver: NameResolver + ?Sized>(
        &self,
        names: &Resolver,
    ) -> Result<TokenStream, Error> {
        let attributes = self.attributes.project_preamble(names)?;
        let visibility = self.visibility.project(names)?;
        let name = self.name.project(names)?;
        let type_reference = self.type_reference.project(names)?;
        let value = self.value.project(names)?;
        Ok(quote! { #attributes #visibility const #name: #type_reference = #value; })
    }
}

impl ProjectRust for Module {
    fn project<Resolver: NameResolver + ?Sized>(
        &self,
        names: &Resolver,
    ) -> Result<TokenStream, Error> {
        let attributes = self.attributes.project_preamble(names)?;
        let visibility = self.visibility.project(names)?;
        let name = self.name.project(names)?;
        let items = self
            .items
            .iter()
            .map(|item| item.project(names))
            .collect::<Result<Vec<_>, _>>()?;
        // The `{…}` inline-module delimiter — a delimiter re-sugaring the owning node
        // chooses.
        Ok(quote! { #attributes #visibility mod #name { #(#items)* } })
    }
}

impl ProjectRust for Use {
    fn project<Resolver: NameResolver + ?Sized>(
        &self,
        names: &Resolver,
    ) -> Result<TokenStream, Error> {
        let attributes = self.attributes.project_preamble(names)?;
        let visibility = self.visibility.project(names)?;
        let base = self.base.project(names)?;
        let group = self
            .group
            .iter()
            .map(|identifier| identifier.project(names))
            .collect::<Result<Vec<_>, _>>()?;
        // The `::` between base and group, and the `{…}` brace group, are the
        // delimiter re-sugaring the owning node chooses.
        Ok(quote! { #attributes #visibility use #base::{ #(#group),* }; })
    }
}

impl ProjectRust for CoreItem {
    fn project<Resolver: NameResolver + ?Sized>(
        &self,
        names: &Resolver,
    ) -> Result<TokenStream, Error> {
        // Exhaustive over the closed algebra — no wildcard arm, so a new item kind
        // is a compile error until its projection is written.
        match self {
            CoreItem::Newtype(newtype) => newtype.project(names),
            CoreItem::Struct(structure) => structure.project(names),
            CoreItem::Enumeration(enumeration) => enumeration.project(names),
            CoreItem::Alias(alias) => alias.project(names),
            CoreItem::ImplBlock(impl_block) => impl_block.project(names),
            CoreItem::Function(function) => function.project(names),
            CoreItem::Use(use_import) => use_import.project(names),
            CoreItem::Const(const_item) => const_item.project(names),
            CoreItem::Module(module) => module.project(names),
        }
    }
}

/// A rendered Rust textual form — the output noun of the writer and the input noun
/// of the reader. It carries the projected Rust source text; formatting is
/// prettyplease's, owned by the constructors here.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct RustSource(String);

impl RustSource {
    /// Wrap already-rendered Rust text (e.g. a golden file read from disk).
    pub fn new(text: impl Into<String>) -> Self {
        Self(text.into())
    }

    /// The rendered text.
    pub fn as_str(&self) -> &str {
        &self.0
    }

    /// Consume into the owned text.
    pub fn into_string(self) -> String {
        self.0
    }

    /// Project one CoreLogos item to byte-exact Rust: assemble its token structure
    /// through [`ProjectRust`], then run the single `prettyplease` pass that owns
    /// all formatting. The attribute preamble (including `#[rustfmt::skip]`) is
    /// stored data on the item, so it is part of the projected tokens, not
    /// prepended here.
    pub fn project_item<Resolver: NameResolver + ?Sized>(
        item: &CoreItem,
        names: &Resolver,
    ) -> Result<Self, Error> {
        let tokens = item.project(names)?;
        let file: syn::File =
            syn::parse2(tokens).map_err(|error| Error::Project(error.to_string()))?;
        Ok(Self(prettyplease::unparse(&file)))
    }

    /// Project several CoreLogos items in a *single* `prettyplease` pass — the
    /// blank-line layout between them is prettyplease's own (consecutive scalar type
    /// aliases pack with no blank; a `use` after them takes no blank either). This is
    /// the block-level render the fixed module prelude needs: the four scalar aliases
    /// as one blank-free block. For a one-item slice it equals [`Self::project_item`].
    pub fn project_items<Resolver: NameResolver + ?Sized>(
        items: &[CoreItem],
        names: &Resolver,
    ) -> Result<Self, Error> {
        let mut tokens = TokenStream::new();
        for item in items {
            tokens.extend(item.project(names)?);
        }
        let file: syn::File =
            syn::parse2(tokens).map_err(|error| Error::Project(error.to_string()))?;
        Ok(Self(prettyplease::unparse(&file)))
    }

    /// Project a whole module: the `// @generated by logos` header (build-stamped
    /// with this crate's own version), then each item's single-pass render,
    /// separated by a blank line — the generated-module shape. Per-item
    /// byte-exactness is the acceptance unit; this is the convenience
    /// whole-module view.
    pub fn project_module<Resolver: NameResolver + ?Sized>(
        items: &[CoreItem],
        names: &Resolver,
    ) -> Result<Self, Error> {
        let mut text = String::new();
        text.push_str(GENERATED_HEADER);
        text.push_str("\n\n");
        for item in items {
            text.push_str(Self::project_item(item, names)?.as_str());
            text.push('\n');
        }
        Ok(Self(text))
    }
}
